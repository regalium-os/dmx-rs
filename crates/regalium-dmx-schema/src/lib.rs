//! The DMX domain model, generated from the protobuf source of truth.
//!
//! `protobuf/` is the authority for what a node, a universe, its levels and
//! an RDM device are, shaped to Google AIP and laid out as bacnet-rs's is:
//! resources first, standard methods over them, custom methods for what is
//! neither. This crate carries the prost types, with protobuf's canonical
//! JSON mapping, and [`convert`], which fills them from what the core knows.
//!
//! # The resources
//!
//! | Resource | Name | Backed by |
//! | --- | --- | --- |
//! | [`node::Node`] | `nodes/artnet-10-0-0-5-1` | an `ArtPoll` reply, an sACN source's discovery, a widget's probe |
//! | [`universe::Universe`] | `universes/stage-left` | a runtime output (patch) or input (listen) |
//! | [`universe::Levels`] | `universes/stage-left/levels` | the universe's slots: read, written, streamed |
//! | [`rdm::Device`] | `…/devices/4c55-12345678` | an RDM responder, found by discovery (E1.20) |
//! | [`rdm::Parameter`] | `…/parameters/dmx-start-address` | one PID, as raw RDM GET and SET |
//! | [`server::Policy`], [`server::ServerStatus`] | `policy`, `serverStatus` | the one output safety policy; the server |
//!
//! The services are declared, not served: the server (Phase 9) serves them.
//!
//! # Concurrency
//!
//! Every type is plain data: `Send`, `Sync`, and safe to share.
//!
//! # Why the core does not import this
//!
//! The protocol layers do not depend on the generated types: that would put
//! prost in the graph of every consumer of the codecs. Conversion lives
//! here and imports the core, not the other way round.
//!
//! # Layer contract
//!
//! Owns: generated types, and the conversions between them and the core's
//! protocol types.
//!
//! Must not: appear in the dependency graph of the core or any transport.
//!
//! Allowed imports: `regalium-dmx-core`, `regalium-dmx-telemetry`.

#[allow(
    missing_docs,
    unreachable_pub,
    clippy::all,
    clippy::pedantic,
    rust_2018_idioms,
    reason = "generated by protoc-gen-prost; the protos are where it is reviewed"
)]
mod generated;

pub mod convert;

/// `dmx.node.v1`: the equipment that carries universes, and its discovery.
pub use generated::dmx::node::v1 as node;
/// `dmx.rdm.v1`: RDM devices and their parameters.
pub use generated::dmx::rdm::v1 as rdm;
/// `dmx.server.v1`: the output policy and the server's status.
pub use generated::dmx::server::v1 as server;
/// `dmx.universe.v1`: universes and their levels. Every message has
/// protobuf's canonical JSON mapping through serde.
pub use generated::dmx::universe::v1 as universe;
